/** Docs for a bare name (print, len, make...) in this language. */
export function globalDocs(language: string): DocTable {
  switch (language) {
    case "python":
      return PY_BUILTINS;
    case "go":
      return GO_BUILTINS;
    case "rust":
      return RUST_MACROS;
    case "cpp":
      return { ...C_FUNCTIONS };
    case "sql":
      return { ...SQL_FUNCTIONS, ...SQL_CLAUSE_DOCS };
    case "csharp":
      return CS_GLOBALS;
    default:
      return {};
  }
}

/** Docs for `owner.name` (module/class member): Console.WriteLine, fmt.Println, math.sqrt, std::cout ... */
export function qualifiedDoc(language: string, owner: string, name: string): DocEntry | undefined {
  switch (language) {
    case "python":
      return PY_MODULES[owner]?.[name];
    case "csharp":
      return CS_MEMBERS[owner]?.[name];
    case "go":
      return GO_PACKAGES[owner]?.[name];
    case "cpp":
      return owner === "std" ? CPP_STD[name] : undefined;
    default:
      return undefined;
  }
}
