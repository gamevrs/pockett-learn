// Builds src/scenes/schema-studio/demo-data.ts: what the Schema Studio scene reads from a FINISHED
// learner program (tables, result sets, statement diary), taken from the real engine so the
// landing-page demo and the hub preview can never drift from what a learner actually sees.
//   node scripts/gen-schema-studio-demo.mjs            (runs the reference solution of every lesson)
//   node scripts/gen-schema-studio-demo.mjs --sql f.sql (runs a file instead; used while authoring)
process.env.NODE_NO_WARNINGS = "1";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";
import { executeSql, describeTables } from "../src/engine/runtimes/sql/engine.ts";
import { solutionThrough } from "../src/engine/compose.ts";
import { flattenLessons } from "../src/engine/types.ts";

const here = fileURLToPath(new URL(".", import.meta.url));
const root = join(here, "..");
const initSqlJs = (await import(pathToFileURL(join(root, "node_modules", "sql.js", "dist", "sql-wasm.js")).href)).default;
const SQL = await initSqlJs();

const sqlFlag = process.argv.indexOf("--sql");
let source;
let setup;
const mod = await import(pathToFileURL(join(root, "src", "content", "projects", "schema-studio.ts")).href).catch(() => null);
const project = mod && Object.values(mod).find((v) => v && typeof v === "object" && v.slug === "schema-studio");
if (sqlFlag >= 0) {
  source = readFileSync(process.argv[sqlFlag + 1], "utf8");
  setup = project?.setup ?? readFileSync(process.argv[sqlFlag + 2], "utf8");
} else {
  source = solutionThrough(project, flattenLessons(project).length - 1);
  setup = project.setup;
}

const run = executeSql(SQL, source, setup);
if (run.error) {
  console.error("The reference solution failed:", run.error);
  process.exit(1);
}
const MAX_ROWS = 40;
const results = run.results.map((r) => ({ sql: r.sql, columns: r.columns, rows: r.rows.slice(0, MAX_ROWS) }));
const data = { tables: describeTables(run.db), results, log: run.log };
run.db.close();

const out = `// GENERATED by scripts/gen-schema-studio-demo.mjs from the reference solution. Do not edit by hand.
export const DEMO_DATA = ${JSON.stringify(data)} as unknown as {
  tables: unknown[];
  results: { sql: string; columns: string[]; rows: unknown[][] }[];
  log: unknown[];
};
`;
writeFileSync(join(root, "src", "scenes", "schema-studio", "demo-data.ts"), out);
console.log(`wrote demo-data.ts: ${data.tables.length} tables, ${results.length} result sets, ${run.log.length} log lines, ${(out.length / 1024).toFixed(0)} KB`);
